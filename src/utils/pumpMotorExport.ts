import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import * as XLSX from 'xlsx';
import type { PumpMotorInputs, CalcValues, BOMItem, ValidationCheck } from './pumpMotorCalc';

type jsPDFWithAutoTable = jsPDF & { lastAutoTable: { finalY: number } };

const PRIMARY: [number, number, number] = [30, 64, 175];
const DARK:    [number, number, number] = [15, 23, 42];
const GRAY:    [number, number, number] = [100, 116, 139];
const SUCCESS: [number, number, number] = [21, 128, 61];
const DANGER:  [number, number, number] = [185, 28, 28];
const WARN:    [number, number, number] = [161, 98, 7];
const GREEN:   [number, number, number] = [16, 185, 129];

function pageHeader(doc: jsPDF, inp: PumpMotorInputs): void {
  const pageW = doc.internal.pageSize.getWidth();
  const margin = 15;
  doc.setFillColor(...PRIMARY);
  doc.rect(0, 0, pageW, 26, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.text('PUMP & MOTOR ELECTRICAL CALCULATION', margin, 9);
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.text(`Project: ${inp.projectName || '—'}  |  No: ${inp.projectNo || '—'}  |  Area: ${inp.plantArea || '—'}`, margin, 16);
  doc.text(`Equipment: ${inp.equipmentName}  |  Pump: ${inp.pumpTag}  |  Motor: ${inp.motorTag}`, margin, 21);
  const date = new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
  doc.text(`Prepared by: ${inp.preparedBy || '—'}  |  Date: ${date}`, pageW - margin, 16, { align: 'right' });
  doc.text(`Generated by ElecCalc Pro`, pageW - margin, 21, { align: 'right' });
}

function sectionTitle(doc: jsPDF, title: string, y: number): number {
  const margin = 15;
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, doc.internal.pageSize.getWidth() - 2 * margin, 9, 'F');
  doc.setTextColor(...DARK);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(title, margin + 3, y + 6.5);
  return y + 13;
}

function checkNewPage(doc: jsPDF, y: number, needed = 40): number {
  if (y + needed > 270) {
    doc.addPage();
    pageHeader(doc, (doc as unknown as { _pmInp: PumpMotorInputs })._pmInp);
    return 34;
  }
  return y;
}

// ── PDF Export ────────────────────────────────────────────────

export function exportPumpMotorPDF(
  inp: PumpMotorInputs,
  calc: CalcValues,
  bom: BOMItem[],
  checks: ValidationCheck[]
): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' }) as jsPDFWithAutoTable;
  (doc as unknown as { _pmInp: PumpMotorInputs })._pmInp = inp;
  const pageW = doc.internal.pageSize.getWidth();
  const margin = 15;

  // Page 1 — Header + Project + Motor Calculation
  pageHeader(doc, inp);
  let y = 34;

  // Disclaimer
  doc.setFillColor(255, 251, 235);
  doc.rect(margin, y, pageW - 2 * margin, 12, 'F');
  doc.setTextColor(...WARN);
  doc.setFontSize(7);
  doc.setFont('helvetica', 'bold');
  doc.text('ENGINEERING DISCLAIMER:', margin + 3, y + 4);
  doc.setFont('helvetica', 'normal');
  const disc = doc.splitTextToSize(
    'Calculated values are engineering design recommendations. All selections must be verified against actual equipment nameplate data, manufacturer recommendations, site conditions, applicable IEC/local standards and short-circuit studies before procurement.',
    pageW - 2 * margin - 6
  );
  doc.text(disc, margin + 3, y + 8);
  y += 16;

  // ── Section 1: Project Details ──────────────────────────
  y = sectionTitle(doc, '1. PROJECT DETAILS', y);
  autoTable(doc, {
    startY: y,
    body: [
      ['Project Name', inp.projectName || '—', 'Project No.', inp.projectNo || '—'],
      ['Plant / Area', inp.plantArea || '—', 'Application', inp.application],
      ['Equipment', inp.equipmentName, 'Quantity', `${inp.quantity} Sets`],
      ['Pump Tag', inp.pumpTag, 'Motor Tag', inp.motorTag],
      ['Prepared By', inp.preparedBy || '—', 'Date', inp.date],
      ['Remarks', inp.remarks || '—', '', ''],
    ],
    theme: 'grid',
    bodyStyles: { fontSize: 8, textColor: DARK },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: { 0: { cellWidth: 35, fontStyle: 'bold', textColor: GRAY }, 1: { cellWidth: 55 }, 2: { cellWidth: 35, fontStyle: 'bold', textColor: GRAY }, 3: { cellWidth: 55 } },
    margin: { left: margin, right: margin },
  });
  y = doc.lastAutoTable.finalY + 8;

  // ── Section 2: Motor Parameters ─────────────────────────
  y = checkNewPage(doc, y, 50);
  y = sectionTitle(doc, '2. MOTOR PARAMETERS', y);
  autoTable(doc, {
    startY: y,
    body: [
      ['Motor Rating', `${inp.motorKW} kW`, 'System Voltage', `${inp.voltage} V`],
      ['Phase', `${inp.phase}-Phase`, 'Frequency', `${inp.frequency} Hz`],
      ['Power Factor', inp.powerFactor.toString(), 'Efficiency', `${inp.efficiency} %`],
      ['Rated Speed', `${inp.rpm} RPM`, 'Motor Duty', inp.motorDuty],
      ['Starting Method', inp.startingMethod, 'Insulation Class', inp.insulationClass],
      ['Motor IP Rating', inp.ipRating, 'Panel IP Rating', inp.panelIP],
      ['Control Voltage', inp.controlVoltage, '', ''],
    ],
    theme: 'grid',
    bodyStyles: { fontSize: 8, textColor: DARK },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: { 0: { cellWidth: 35, fontStyle: 'bold', textColor: GRAY }, 1: { cellWidth: 55 }, 2: { cellWidth: 35, fontStyle: 'bold', textColor: GRAY }, 3: { cellWidth: 55 } },
    margin: { left: margin, right: margin },
  });
  y = doc.lastAutoTable.finalY + 8;

  // ── Section 3: Motor Electrical Calculation ─────────────
  y = checkNewPage(doc, y, 50);
  y = sectionTitle(doc, '3. MOTOR ELECTRICAL CALCULATION', y);

  // Formula box
  const formula = inp.phase === '3'
    ? `I = P ÷ (√3 × V × PF × η) = ${inp.motorKW * 1000} ÷ (1.732 × ${inp.voltage} × ${inp.powerFactor} × ${(inp.efficiency / 100).toFixed(2)}) = ${calc.flc} A`
    : `I = P ÷ (V × PF × η) = ${inp.motorKW * 1000} ÷ (${inp.voltage} × ${inp.powerFactor} × ${(inp.efficiency / 100).toFixed(2)}) = ${calc.flc} A`;
  doc.setFillColor(239, 246, 255);
  doc.rect(margin, y, pageW - 2 * margin, 10, 'F');
  doc.setTextColor(...PRIMARY);
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.text(`Formula: ${formula}`, margin + 3, y + 6.5);
  y += 14;

  autoTable(doc, {
    startY: y,
    head: [['Parameter', 'Calculated Value', 'Note']],
    body: [
      ['Full Load Current (FLC)', `${calc.flc} A`, 'Per IEC 60364-4-43'],
      ['Design Current (125% × FLC)', `${calc.designCurrent} A`, 'For protection sizing'],
      ['Starting Current', `${calc.startingCurrent} A`, `${inp.startingMethod} method — design estimate`],
      ['Derating Factor', calc.deratingFactor.toString(), `Temp ${inp.ambientTemp}°C × Group ${inp.groupingFactor}`],
    ],
    theme: 'grid',
    headStyles: { fillColor: PRIMARY, textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
    bodyStyles: { fontSize: 8, textColor: DARK },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: { 0: { cellWidth: 70, fontStyle: 'bold' }, 1: { cellWidth: 40 }, 2: { cellWidth: 70 } },
    margin: { left: margin, right: margin },
  });
  y = doc.lastAutoTable.finalY + 8;

  // ── Section 4: Protection Selection ─────────────────────
  y = checkNewPage(doc, y, 50);
  y = sectionTitle(doc, '4. PROTECTION SELECTION', y);
  autoTable(doc, {
    startY: y,
    head: [['Device', 'Auto Selection', 'Override', 'Specification']],
    body: [
      ['MCCB', `${calc.mccbRating} A`, inp.mccbOverride > 0 ? `${inp.mccbOverride} A (Manual)` : 'Auto', `3P, Motor Duty, Min 25 kA BC, ${inp.voltage} V`],
      ['Contactor (AC-3)', `${calc.contactorRating} A`, inp.contactorOverride > 0 ? `${inp.contactorOverride} A (Manual)` : 'Auto', `AC-3, ${inp.controlVoltage} coil, 2NO+2NC aux`],
      ['Overload Relay', `${calc.olrRange[0]}–${calc.olrRange[1]} A`, inp.olrOverrideLow > 0 ? `${inp.olrOverrideLow}–${inp.olrOverrideHigh} A (Manual)` : 'Auto', `Class 10, set at ${calc.olrSetting} A, manual+auto reset`],
    ],
    theme: 'grid',
    headStyles: { fillColor: [51, 65, 85], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
    bodyStyles: { fontSize: 8, textColor: DARK },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: { 0: { cellWidth: 35, fontStyle: 'bold' }, 1: { cellWidth: 35 }, 2: { cellWidth: 40 }, 3: { cellWidth: 70 } },
    margin: { left: margin, right: margin },
  });
  y = doc.lastAutoTable.finalY + 8;

  // ── Section 5: Cable Calculation ─────────────────────────
  y = checkNewPage(doc, y, 70);
  y = sectionTitle(doc, '5. CABLE CALCULATION', y);
  autoTable(doc, {
    startY: y,
    head: [['Parameter', 'Value', 'Parameter', 'Value']],
    body: [
      ['Cable Length', `${inp.cableLength} m`, 'Installation Method', inp.installMethod],
      ['Cable Material', inp.cableMaterial, 'Insulation', inp.cableInsulation],
      ['Ambient Temperature', `${inp.ambientTemp} °C`, 'Grouping Factor', inp.groupingFactor.toString()],
      ['Number of Cores', inp.numCores.toString(), 'Parallel Runs', inp.parallelRuns.toString()],
      ['Max Voltage Drop', `${inp.maxVoltageDrop} %`, '', ''],
      ['', '', '', ''],
      ['Recommended Cable Size', `${calc.cableSize} mm² ${inp.cableMaterial} ${inp.cableInsulation}`, 'Earth Cable Size', `${calc.earthSize} mm²`],
      ['Derated Ampacity', `${calc.cableAmpacity} A`, 'Design Current', `${calc.designCurrent} A`],
      ['Voltage Drop', `${calc.voltageDrop} V`, 'Voltage Drop %', `${calc.voltageDropPct} %`],
      ['Cable Resistance', `${calc.cableResistance} Ω`, 'Cable Reactance', `${calc.cableReactance} Ω`],
    ],
    theme: 'grid',
    headStyles: { fillColor: PRIMARY, textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
    bodyStyles: { fontSize: 8, textColor: DARK },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: { 0: { cellWidth: 45, fontStyle: 'bold', textColor: GRAY }, 1: { cellWidth: 45 }, 2: { cellWidth: 45, fontStyle: 'bold', textColor: GRAY }, 3: { cellWidth: 45 } },
    margin: { left: margin, right: margin },
    didParseCell: (data) => {
      if (data.section === 'body' && data.row.index === 8 && data.column.index === 3) {
        data.cell.styles.fontStyle = 'bold';
        data.cell.styles.textColor = calc.voltageDropPct <= inp.maxVoltageDrop ? SUCCESS : DANGER;
      }
    },
  });
  y = doc.lastAutoTable.finalY + 8;

  // ── Section 6: Validation ────────────────────────────────
  doc.addPage();
  pageHeader(doc, inp);
  y = 34;
  y = sectionTitle(doc, '6. VALIDATION CHECKS', y);

  const passCount = checks.filter((c) => c.status === 'PASS').length;
  const warnCount = checks.filter((c) => c.status === 'WARNING').length;
  const failCount = checks.filter((c) => c.status === 'FAIL').length;

  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...DARK);
  doc.text(`Total: ${checks.length} checks   Pass: ${passCount}   Warnings: ${warnCount}   Fail: ${failCount}`, margin, y);
  y += 8;

  autoTable(doc, {
    startY: y,
    head: [['Category', 'Check', 'Calculated', 'Limit', 'Status']],
    body: checks.map((c) => [c.category, c.description, c.calculated, c.limit, c.status]),
    theme: 'grid',
    headStyles: { fillColor: [51, 65, 85], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
    bodyStyles: { fontSize: 7.5, textColor: DARK },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: { 0: { cellWidth: 22 }, 1: { cellWidth: 55 }, 2: { cellWidth: 30 }, 3: { cellWidth: 35 }, 4: { cellWidth: 18, fontStyle: 'bold' } },
    margin: { left: margin, right: margin },
    didParseCell: (data) => {
      if (data.section === 'body' && data.column.index === 4) {
        const s = data.cell.text[0];
        data.cell.styles.textColor = s === 'PASS' ? SUCCESS : s === 'FAIL' ? DANGER : WARN;
      }
    },
  });
  y = doc.lastAutoTable.finalY + 8;

  // ── Section 7: Complete BOM ──────────────────────────────
  doc.addPage();
  pageHeader(doc, inp);
  y = 34;
  y = sectionTitle(doc, '7. COMPLETE BILL OF MATERIALS (BOM)', y);

  autoTable(doc, {
    startY: y,
    head: [['Sl', 'Category', 'Description', 'Specification', 'Qty', 'Unit', 'Basis']],
    body: bom.map((item) => [
      item.slNo,
      item.category,
      item.description,
      item.specification,
      item.qty,
      item.unit,
      item.basis,
    ]),
    theme: 'striped',
    headStyles: { fillColor: PRIMARY, textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 7.5 },
    bodyStyles: { fontSize: 7, textColor: DARK },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    columnStyles: {
      0: { cellWidth: 8 },
      1: { cellWidth: 25, fontStyle: 'bold', textColor: [30, 64, 175] },
      2: { cellWidth: 38 },
      3: { cellWidth: 60 },
      4: { cellWidth: 10, halign: 'right', fontStyle: 'bold' },
      5: { cellWidth: 10 },
      6: { cellWidth: 29 },
    },
    margin: { left: margin, right: margin },
    didParseCell: (data) => {
      if (data.section === 'body' && data.column.index === 4) {
        data.cell.styles.fontStyle = 'bold';
      }
    },
  });
  y = doc.lastAutoTable.finalY + 10;

  // Summary box
  if (y + 30 > 270) { doc.addPage(); pageHeader(doc, inp); y = 34; }
  doc.setFillColor(...GREEN);
  doc.rect(margin, y, pageW - 2 * margin, 12, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`TOTAL BOM ITEMS: ${bom.length}   |   Motor: ${inp.motorKW} kW   |   Cable: ${calc.cableSize} mm²   |   MCCB: ${calc.mccbRating} A   |   VD: ${calc.voltageDropPct}%`, margin + 4, y + 7.5);
  y += 16;

  // Engineering notes
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...DARK);
  doc.text('ENGINEERING NOTES:', margin, y);
  y += 5;
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  const notes = [
    '1. All calculations are based on IEC 60364, IEC 60947 and IEC 60228 standards.',
    '2. Cable ampacity from IEC 60364-5-52 Tables, derated for ambient temperature and grouping.',
    '3. Starting currents are design estimates — verify with motor manufacturer nameplate data.',
    '4. MCCB, contactor and OLR ratings are minimum recommendations — select next commercial size available.',
    '5. All material quantities include reasonable allowances. Verify against actual site measurements.',
    '6. Final settings must be commissioned by a qualified electrical engineer.',
  ];
  notes.forEach((n) => { doc.text(n, margin, y); y += 5; });

  // Signature
  y = Math.max(y + 8, 255);
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.3);
  doc.line(margin, y, margin + 70, y);
  doc.line(pageW / 2, y, pageW / 2 + 70, y);
  doc.setFontSize(8);
  doc.setTextColor(...GRAY);
  doc.text(`Prepared by: ${inp.preparedBy || '___________'}`, margin, y + 5);
  doc.text('Approved by: ___________________', pageW / 2, y + 5);
  doc.text(`Date: ${new Date().toLocaleDateString('en-GB')}`, margin, y + 10);
  doc.text('Revision: A', pageW / 2, y + 10);

  // Footer on all pages
  const total = doc.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    doc.setPage(i);
    doc.setFillColor(248, 250, 252);
    doc.rect(0, 285, pageW, 12, 'F');
    doc.setFontSize(7);
    doc.setTextColor(...GRAY);
    doc.text(`ElecCalc Pro  |  Pump & Motor Electrical Calculator  |  ${inp.projectName || 'Untitled'}  |  ${new Date().toISOString().split('T')[0]}`, margin, 291);
    doc.text(`Page ${i} of ${total}`, pageW - margin, 291, { align: 'right' });
  }

  doc.save(`PumpMotor_${inp.pumpTag || 'CALC'}_${Date.now()}.pdf`);
}

